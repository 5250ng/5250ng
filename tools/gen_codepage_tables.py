"""Generate the EBCDIC graphic-range tables in src/core/codepage_tables.inc.

Each byte 0x40-0xFF is decoded with ICU (uconv), whose ibm-* tables are
IBM's CDRA mappings. glibc iconv and Python's codecs (where they have the
code page) are compared and every difference is printed to stderr; they
disagree with ICU on a few bytes (e.g. CP278 0x71/0xE0, the CP424
punctuation), and IBM's own Java charsets agree with ICU on each of them.
CP838 has no iconv table, so it is compared with IBM1160 (838 plus the euro
sign at 0xFE). Bytes that decode to a control character, or that ICU leaves
undefined, are written as 0 (unmapped). A character found at two bytes
(only the CP838 tone marks) gets a kCPxxxPreferred entry with the byte ICU
encodes it to.

Usage: tools/gen_codepage_tables.py > src/core/codepage_tables.inc
"""
import codecs
import subprocess
import sys

PAGES = [37, 273, 277, 278, 280, 284, 285, 297, 500, 870, 420, 424, 838]
ICONV_NAME = {838: "IBM1160"}
ICONV_DIFFERS = {838: {0xFE}}  # IBM1160 has the euro sign at 0xFE
DUPLICATES_ALLOWED = {838}  # five Thai tone marks at two bytes each


def decode(cmd, byte):
    r = subprocess.run(cmd, input=bytes([byte]), capture_output=True)
    if r.returncode != 0 or len(r.stdout) != 2:
        return None
    return int.from_bytes(r.stdout, "big")


def icu(page, byte):
    return decode(["uconv", "--from-callback", "stop", "-f", "ibm-%d" % page, "-t", "UTF-16BE"], byte)


def iconv(page, byte):
    name = ICONV_NAME.get(page, "IBM%03d" % page)
    return decode(["iconv", "-f", name, "-t", "UTF-16BE"], byte)


def python(page, byte):
    try:
        codecs.lookup("cp%03d" % page)
    except LookupError:
        return "n/a"
    try:
        return ord(bytes([byte]).decode("cp%03d" % page))
    except UnicodeDecodeError:
        return None


def icu_encode(page, u):
    r = subprocess.run(["uconv", "--to-callback", "stop", "-f", "UTF-16BE", "-t", "ibm-%d" % page],
                       input=u.to_bytes(2, "big"), capture_output=True)
    return r.stdout[0] if r.returncode == 0 and len(r.stdout) == 1 else None


def graphic(u):
    return u is not None and u >= 0x20 and not (0x7F <= u <= 0x9F)


def main():
    notes = []
    out = ["// Generated by tools/gen_codepage_tables.py from ICU's ibm-* tables",
           "// (uconv). Do not edit by hand; re-run the script instead.",
           "// EBCDIC bytes 0x40-0xFF; 0 = unmapped or a control character."]
    for page in PAGES:
        row = []
        for b in range(0x40, 0x100):
            u, i, p = icu(page, b), iconv(page, b), python(page, b)
            if b not in ICONV_DIFFERS.get(page, set()) and i != u:
                notes.append("CP%03d 0x%02X: ICU %s, iconv %s" % (page, b, u, i))
            if p != "n/a" and p != u:
                notes.append("CP%03d 0x%02X: ICU %s, Python %s" % (page, b, u, p))
            row.append(u if graphic(u) else 0)
        out.append("static constexpr uint16_t kCP%03d[192] = {" % page)
        for k in range(0, 192, 8):
            out.append("    " + ", ".join("0x%04X" % v for v in row[k:k + 8]) + ",")
        out.append("};")
        # A character at two bytes encodes to the byte ICU chooses
        dups = sorted({v for v in row if v and row.count(v) > 1})
        if dups:
            if page not in DUPLICATES_ALLOWED:
                sys.exit("CP%03d has characters at two bytes; add it to DUPLICATES_ALLOWED" % page)
            out.append("static constexpr uint16_t kCP%03dPreferred[][2] = {" % page)
            for v in dups:
                out.append("    {0x%04X, 0x%02X}," % (v, icu_encode(page, v)))
            out.append("};")
    if notes:
        sys.stderr.write("Differences from ICU (ICU is used):\n" + "\n".join(notes) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
