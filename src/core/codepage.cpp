void CodePage::initCP285() {
    // CP285 - United Kingdom
    initCP037(); // base
    t(0x4A)=0x0024; // $ (was ¢ in 037)
    t(0x5B)=0x00A3; // £ (was $ in 037)
    t(0x7B)=0x00AF; // ¯ (was # in 037)
    t(0xB1)=0x0023; // # (was £ in 037)
}

