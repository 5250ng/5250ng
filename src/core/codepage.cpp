void CodePage::initCP273() {
    // CP273 - Germany/Austria — same as 037 but with German special chars
    initCP037(); // Start with CP037 as base
    // Override German-specific positions
    t(0x4A)=0x00C4; // Ä (was ¢ in 037)
    t(0x4F)=0x0021; // ! (was | in 037)
    t(0x5A)=0x00D6; // Ö (was ! in 037)
    t(0x5B)=0x00DC; // Ü (was $ in 037)
    t(0x5F)=0x00D7; // × (was ^ in 037) — multiply sign, not ^
    // TODO: verify these against IBM docs
    t(0x6A)=0x00FC; // ü (was ¦ in 037)
    t(0x79)=0x00E4; // ä (was ` in 037)
    t(0x7B)=0x00A7; // § (was # in 037)
    t(0x7C)=0x00F6; // ö (was @ in 037)
    t(0xA1)=0x00DF; // ß (was ~ in 037)
    t(0xB5)=0x0040; // @ (was § in 037)
    t(0xC0)=0x007B; // {
    t(0xD0)=0x007D; // }
    t(0xE0)=0x005C; // backslash
}

